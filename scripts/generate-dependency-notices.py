#!/usr/bin/env python3
"""Generate/check release notices from Gradle-resolved POMs and binary archives.

Run the companion Gradle inventory task first. No source/account data is read.
Unknown licences or missing metadata fail closed and require a reviewed update.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / 'app/build/reports/publication-dependencies.json'
OUTPUT = ROOT / 'app/src/main/assets/licenses/dependency-notices.txt'
GUAVA_PARENT = 'https://repo.maven.apache.org/maven2/com/google/guava/guava-parent/26.0-android/guava-parent-26.0-android.pom'
APACHE_NAMES = {'apache-2.0', 'the apache software license, version 2.0',
                'the apache license, version 2.0', 'apache 2.0',
                'apache license, version 2.0', 'apache license 2.0 (inherited)'}
PSL_COORDINATE = 'com.squareup.okhttp3:okhttp-android:5.5.0'
PSL_SHA256 = 'c75ab827afd7ffff59a51b14729c25dbfc3b45237eb40ccf02bec7b7d44304a4'


def check_public_suffix(coordinate, data):
    """Bind supplemental source attribution to the reviewed embedded dataset."""
    if coordinate.startswith('com.squareup.okhttp3:okhttp-android:'):
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            digest = hashlib.sha256(archive.read('assets/PublicSuffixDatabase.list')).hexdigest()
        if coordinate != PSL_COORDINATE or digest != PSL_SHA256:
            raise ValueError('Review updated Public Suffix corresponding source and notice')


def normalise(text):
    return '\n'.join(line.rstrip() for line in text.splitlines()).strip() + '\n'


def pom_licenses(coordinate, path):
    if not path:
        raise ValueError(f'Missing POM: {coordinate}')
    root = ET.parse(path).getroot()
    for element in root.iter():
        element.tag = element.tag.rsplit('}', 1)[-1]
    licenses = [(x.findtext('name', ''), x.findtext('url', ''))
                for x in root.findall('licenses/license')]
    if not licenses and coordinate == 'com.google.guava:listenablefuture:1.0':
        parent = root.find('parent')
        if parent is not None and [parent.findtext(k) for k in ('groupId', 'artifactId', 'version')] == ['com.google.guava', 'guava-parent', '26.0-android']:
            licenses = [('Apache License 2.0 (inherited)', GUAVA_PARENT)]
    if not licenses:
        raise ValueError(f'Unresolved licence: {coordinate}')
    for name, url in licenses:
        if name.strip().lower() not in APACHE_NAMES:
            raise ValueError(f'New licence requires review: {coordinate}: {name}')
    return sorted(licenses)


def archive_notices(data, prefix='', depth=0):
    if depth > 5:
        raise ValueError('Nested archive depth exceeds reviewed bound')
    result = []
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        for name in sorted(archive.namelist()):
            if name.endswith('/'):
                continue
            if re.search(r'(^|/)(license|notice|copying|copyright)([._-]|$)', name, re.I):
                result.append((prefix + name, normalise(archive.read(name).decode('utf-8'))))
            elif name.endswith(('.jar', '.zip')):
                result.extend(archive_notices(archive.read(name), prefix + name + '!', depth + 1))
    return result


def generate(inventory):
    components = sorted(inventory['components'], key=lambda c: c['coordinate'])
    if not components or not inventory['artifacts']:
        raise ValueError('Empty release inventory')
    lines = ['Release runtime dependency notices', '',
             'Generated by scripts/generate-dependency-notices.py. Do not edit by hand.',
             'This conservative inventory includes metadata/BOM components and artifacts',
             'before R8 shrinking, so some listed components may not remain in the APK.',
             'Published module licences: Apache-2.0. Full text: Apache-2.0.txt.',
             'Additional embedded Public Suffix List terms: MPL-2.0.txt and public-suffix-NOTICE.txt.',
             'Font licences are in adjacent OFL files.', '', 'Components', '']
    for c in components:
        lines.append(c['coordinate'])
        for name, url in pom_licenses(c['coordinate'], c['pom']):
            lines.append(f'  {name}: {url}')
    lines.extend(['', 'Resolved artifact checksums', ''])
    for name in ('Apache-2.0.txt', 'MPL-2.0.txt', 'public-suffix-NOTICE.txt'):
        data = (OUTPUT.parent / name).read_bytes()
        lines.append(f'Supplemental {name}: SHA-256 {hashlib.sha256(data).hexdigest()}')
    notices = {}
    artifacts = sorted(inventory['artifacts'], key=lambda a: (a['coordinate'], Path(a['file']).name))
    for a in artifacts:
        data = Path(a['file']).read_bytes()
        check_public_suffix(a['coordinate'], data)
        lines.append(f"{a['coordinate']} / {Path(a['file']).name}: SHA-256 {hashlib.sha256(data).hexdigest()}")
        for path, content in archive_notices(data):
            notices.setdefault(content, set()).add(a['coordinate'] + '!' + path)
    lines.extend(['', 'Embedded licence and attribution texts', ''])
    for content, origins in sorted(notices.items(), key=lambda pair: sorted(pair[1])):
        lines.extend(['Included by:', *('  ' + origin for origin in sorted(origins)), '', content, ''])
    return normalise('\n'.join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if committed notices differ from resolved dependencies')
    args = parser.parse_args()
    try:
        result = generate(json.loads(INVENTORY.read_text()))
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text() != result:
                raise ValueError('Dependency notices are stale; regenerate and review them')
            print('Release dependency notices match resolved metadata and artifact notices')
        else:
            OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            OUTPUT.write_text(result)
            print('Generated ' + str(OUTPUT.relative_to(ROOT)))
    except (ValueError, OSError, KeyError, ET.ParseError, zipfile.BadZipFile) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
